"""
Generate a simple MuJoCo model of the Crab FYP hexapod.

Every size and mass is a named number below, like the Fusion parameters.
Change a number, re-run this script, and crab.xml is rebuilt.

    python gen_crab.py          -> writes crab.xml next to this file

Frames: x = forward, y = left, z = up. Lengths in mm here, written to
the XML in metres. Angles in degrees here, radians in the XML.
"""
import math
from pathlib import Path

# ---------------------------------------------------------------- body layout
LEG_PITCH   = 120.0   # front-to-middle and middle-to-back hip spacing
BODY_WIDTH  = 170.0   # distance between left and right hip lines
FAN_ANGLE   = 45.0    # corner legs angled outward from straight sideways

# Body collision box (plates + servos sandwiched + electronics).
BODY_LEN    = 280.0   # covers the corner pockets
BODY_WID    = 200.0
BODY_THICK  = 45.0    # plate + servo + plate

# ---------------------------------------------------------------- leg lengths
COXA_LEN    = 50.0    # hip yaw axis -> femur pitch axis   (ESTIMATE, measure in CAD)
FEMUR_LEN   = 75.0    # femur pitch axis -> knee axis       (femur_len)
TIBIA_LEN   = 80.0    # knee axis -> bottom of calf         (tibia_len)
FOOT_EXTRA  = 10.0    # calf bottom -> ground contact point (foot sticks out ~8-10)
FOOT_RADIUS = 10.0    # TPU foot, 20 mm diameter

# ---------------------------------------------------------------- joint limits
HIP_RANGE   = 30.0    # +/- hip yaw    (neighbour clearance test)
FEMUR_RANGE = 60.0    # +/- femur pitch
TIBIA_RANGE = 60.0    # +/- knee

# ---------------------------------------------------------------- masses (kg)
SERVO_MASS  = 0.055
# Body: 6 hip servos + plates/standoffs + battery + fuse box + boards + wiring
BODY_MASS   = 6 * SERVO_MASS + 0.25 + 0.18 + 0.15 + 0.15
COXA_MASS   = SERVO_MASS + 0.025   # pitch servo + hip bracket + thigh
FEMUR_MASS  = SERVO_MASS + 0.035   # knee servo + femur + thigh copy
TIBIA_MASS  = 0.030                # calf + foot

# ---------------------------------------------------------------- servo model
# STS3215 C018 at 12 V: ~30 kg.cm stall = ~2.9 N.m.
SERVO_TORQUE = 2.9     # N.m, actuator force limit
SERVO_KP     = 10.0    # N.m/rad position gain   (tune against real servo)
JOINT_DAMP   = 0.3     # N.m.s/rad
ARMATURE     = 0.005   # reflected rotor inertia (guess)
FRICTIONLOSS = 0.03    # N.m

FOOT_FRICTION = 1.0    # TPU on floor (guess)

# ------------------------------------------------------------------ helpers
mm = lambda v: v / 1000.0
deg = math.radians


def f(*vals):
    return " ".join(f"{v:.5g}" for v in vals)


def hips():
    """(name, x, y, yaw_deg) for each of the 6 legs."""
    hx, hy = LEG_PITCH, BODY_WIDTH / 2
    return [
        ("FL",  hx,  hy,  90 - FAN_ANGLE),
        ("ML", 0.0,  hy,  90),
        ("RL", -hx,  hy,  90 + FAN_ANGLE),
        ("FR",  hx, -hy, -(90 - FAN_ANGLE)),
        ("MR", 0.0, -hy, -90),
        ("RR", -hx, -hy, -(90 + FAN_ANGLE)),
    ]


def leg_xml(name, x, y, yaw):
    c = math.cos(deg(yaw) / 2)
    s = math.sin(deg(yaw) / 2)
    tib = TIBIA_LEN + FOOT_EXTRA - FOOT_RADIUS
    return f"""
    <body name="{name}_coxa" pos="{f(mm(x), mm(y), 0)}" quat="{f(c, 0, 0, s)}">
      <joint name="{name}_hip" class="hip"/>
      <geom name="{name}_coxa_g" type="box" size="{f(mm(COXA_LEN/2), mm(12), mm(17))}"
            pos="{f(mm(COXA_LEN/2), 0, 0)}" mass="{COXA_MASS}" class="link"/>
      <body name="{name}_femur" pos="{f(mm(COXA_LEN), 0, 0)}">
        <joint name="{name}_femur" class="pitch" range="{-FEMUR_RANGE} {FEMUR_RANGE}"/>
        <geom name="{name}_femur_g" type="capsule" fromto="0 0 0 {f(mm(FEMUR_LEN), 0, 0)}"
              size="{mm(12)}" mass="{FEMUR_MASS}" class="link"/>
        <body name="{name}_tibia" pos="{f(mm(FEMUR_LEN), 0, 0)}">
          <joint name="{name}_tibia" class="pitch" range="{-TIBIA_RANGE} {TIBIA_RANGE}"/>
          <geom name="{name}_tibia_g" type="capsule" fromto="0 0 0 0 0 {f(-mm(tib))}"
                size="{mm(8)}" mass="{TIBIA_MASS}" class="link"/>
          <geom name="{name}_foot" type="sphere" pos="{f(0, 0, -mm(tib))}"
                size="{mm(FOOT_RADIUS)}" mass="0.005" class="foot"/>
          <site name="{name}_foot_site" pos="{f(0, 0, -mm(tib))}" size="{mm(FOOT_RADIUS)+0.001}" type="sphere" rgba="0 0 0 0"/>
        </body>
      </body>
    </body>"""


def build():
    legs = hips()
    stand_z = mm(TIBIA_LEN + FOOT_EXTRA) + 0.002
    leg_bodies = "".join(leg_xml(*l) for l in legs)

    actuators = "\n".join(
        f'    <position name="{n}_{j}" joint="{n}_{j}" class="servo"/>'
        for n, *_ in legs for j in ("hip", "femur", "tibia"))

    sensors = "\n".join(
        [f'    <touch name="{n}_contact" site="{n}_foot_site"/>' for n, *_ in legs])

    return f"""<mujoco model="crab_hexapod">
  <!-- Generated by gen_crab.py. Edit the numbers there, not here. -->
  <compiler angle="degree" autolimits="true"/>
  <option timestep="0.002" integrator="implicitfast"/>

  <default>
    <joint damping="{JOINT_DAMP}" armature="{ARMATURE}" frictionloss="{FRICTIONLOSS}"/>
    <!-- robot geoms collide with the floor only, not with each other (turn on later) -->
    <geom contype="2" conaffinity="1" friction="{FOOT_FRICTION} 0.02 0.001"/>
    <default class="hip">
      <joint axis="0 0 1" range="{-HIP_RANGE} {HIP_RANGE}"/>
    </default>
    <default class="pitch">
      <!-- +angle lifts the link up -->
      <joint axis="0 -1 0"/>
    </default>
    <default class="link"><geom rgba="0.2 0.2 0.22 1"/></default>
    <default class="foot"><geom rgba="0.05 0.05 0.05 1" condim="3"/></default>
    <default class="servo">
      <position kp="{SERVO_KP}" forcerange="{-SERVO_TORQUE} {SERVO_TORQUE}"/>
    </default>
  </default>

  <asset>
    <texture name="grid" type="2d" builtin="checker" rgb1=".85 .85 .85" rgb2=".75 .75 .75" width="300" height="300"/>
    <material name="grid" texture="grid" texrepeat="8 8" reflectance="0.1"/>
  </asset>

  <worldbody>
    <light pos="0 0 2" dir="0 0 -1" directional="true"/>
    <geom name="floor" type="plane" size="5 5 0.1" material="grid" contype="1" conaffinity="2"/>

    <body name="base_link" pos="0 0 {stand_z:.4f}">
      <freejoint name="root"/>
      <geom name="body_g" type="box" size="{f(mm(BODY_LEN/2), mm(BODY_WID/2), mm(BODY_THICK/2))}"
            mass="{BODY_MASS:.3f}" rgba="0.15 0.15 0.15 1"/>
      <site name="imu" pos="0 0 0" size="0.005"/>
{leg_bodies}
    </body>
  </worldbody>

  <actuator>
{actuators}
  </actuator>

  <sensor>
    <framequat name="body_quat" objtype="site" objname="imu"/>
    <gyro name="body_gyro" site="imu"/>
    <accelerometer name="body_acc" site="imu"/>
{sensors}
  </sensor>

  <keyframe>
    <!-- femurs level, tibias straight down -->
    <key name="stand" qpos="0 0 {stand_z:.4f} 1 0 0 0 {' '.join(['0'] * 18)}"/>
  </keyframe>
</mujoco>
"""


if __name__ == "__main__":
    out = Path(__file__).with_name("crab.xml")
    out.write_text(build())
    print(f"wrote {out}")
